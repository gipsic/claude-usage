// Emit the web/ directory as a JS module that registers every asset on
// globalThis, so a single-file build can serve the dashboard from memory.
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const ROOT = path.join(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const WEB = path.join(ROOT, 'web');
const out = process.argv[2];
if (!out) {
  console.error('usage: inline-web.mjs <output.cjs>');
  process.exit(1);
}

const assets = {};
for (const name of fs.readdirSync(WEB)) {
  const file = path.join(WEB, name);
  if (!fs.statSync(file).isFile()) continue;
  assets[name] = fs.readFileSync(file).toString('base64');
}

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out,
  `// generated by bin/inline-web.mjs - do not edit\n` +
  `globalThis.__CLAUDE_USAGE_WEB = ${JSON.stringify(assets)};\n` +
  `module.exports = {};\n`);

const bytes = Object.values(assets).reduce((n, b) => n + Buffer.from(b, 'base64').length, 0);
console.log(`    inlined ${Object.keys(assets).length} web assets (${(bytes / 1024).toFixed(0)} kB)`);
